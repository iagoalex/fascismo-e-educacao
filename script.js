// 1. Injeta dinamicamente os 55 botões no menu lateral

function generateMenuButtons() {
  navList.innerHTML = "";
  Object.keys(pages).forEach((key, index) => {
    const page = pages[key];
    const button = document.createElement("button");
    button.className = "nav-item";
    button.dataset.page = key;
    button.textContent = `${page.label} - ${page.title}`;
    
    button.addEventListener("click", () => {
      render(key);
      sidebar.classList.remove("open");
      mobileMenu.setAttribute("aria-expanded", "false");
    });

    navList.appendChild(button);
  });
}

// 2. Função de normalização para busca sem acentos

function normalizeText(text) {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

// 3. Sistema de filtragem e pesquisa nas 55 opções

function filterSessions() {
  const term = normalizeText(searchInput.value);
  const buttons = navList.querySelectorAll(".nav-item");
  let matches = 0;

  buttons.forEach(button => {
    const title = normalizeText(button.textContent);
    const match = !term || title.includes(term);

    button.classList.toggle("search-hidden", !match);
    button.classList.toggle("search-match", Boolean(term && match));

    if (match) matches++;
  });

  clearSearch.style.display = term ? "block" : "none";

  if (!term) {
    searchResult.textContent = "55 seções disponíveis";
  } else if (matches === 0) {
    searchResult.textContent = "Nenhuma seção encontrada";
  } else if (matches === 1) {
    searchResult.textContent = "1 seção encontrada";
  } else {
    searchResult.textContent = `${matches} seções encontradas`;
  }
}

// 4. Renderização do conteúdo da página selecionada

function render(pageName) {
  const page = pages[pageName] || pages["01-inicio"];

  content.innerHTML = `
    <div class="hero">
      <div>
        <div class="eyebrow">${page.label}</div>
        <h1>${page.title}</h1>
      </div>
    </div>
    ${page.body}
  `;

  const buttons = navList.querySelectorAll(".nav-item");
  buttons.forEach(button => {
    button.classList.toggle("active", button.dataset.page === pageName);
  });

  content.focus({ preventScroll: true });
  window.scrollTo({ top: 0, behavior: "smooth" });
}

// Event Listeners de busca

searchInput.addEventListener("input", filterSessions);
clearSearch.addEventListener("click", () => {
  searchInput.value = "";
  filterSessions();
  searchInput.focus();
});

// Event Listener para Menu Mobile

mobileMenu.addEventListener("click", () => {
  const isOpen = sidebar.classList.toggle("open");
  mobileMenu.setAttribute("aria-expanded", String(isOpen));
});


(function integrateIndependentEditor(){
  const KEY = "editor-conteudo-independente-v1";
  const originalPages = window.pages || pages;
  if (typeof originalPages === "undefined") return;

  function esc(v){return String(v||"").replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;").replaceAll('"',"&quot;").replaceAll("'","&#039;");}
  function load(){
    try { return JSON.parse(localStorage.getItem(KEY)) || {menus:[]}; } catch(e){ return {menus:[]}; }
  }
  function addCustomPages(){
    Object.keys(originalPages).filter(k=>k.startsWith("custom-")).forEach(k=>delete originalPages[k]);
    const data=load();
    (data.menus||[]).forEach((m,i)=>{
      const id="custom-"+m.id;
      originalPages[id]={
        label:`Conteúdo personalizado • ${i+1}`,
        title:esc(m.title||"Menu sem título"),
        body:`<section class="section"><div class="section-label">Conteúdo</div>${m.text?`<p>${esc(m.text).replace(/\n/g,"<br>")}</p>`:"<p>Este menu ainda não possui texto.</p>"}${m.image?`<div class="custom-image-wrap"><img class="custom-image" src="${m.image}" alt="${esc(m.title||"Imagem")}"></div>`:""}</section>${m.indications?`<section class="section"><div class="section-label">Indicações</div><h2>Indicações e materiais</h2><div class="note">${esc(m.indications).replace(/\n/g,"<br>")}</div></section>`:""}`
      };
    });
  }
  function rebuild(){
    addCustomPages();
    const navContainer = document.getElementById("navList");
    if(!navContainer) return;
    navContainer.querySelectorAll(".custom-nav-item").forEach(x=>x.remove());
    Object.keys(originalPages).filter(k=>k.startsWith("custom-")).forEach(k=>{
      const b=document.createElement("button");
      b.className="nav-item custom-nav-item";
      b.dataset.page=k;
      b.textContent=originalPages[k].title.replace(/<br\s*\/?>/gi," ");
      b.addEventListener("click",()=>{
        if(typeof render==="function") render(k);
        const sidebar=document.getElementById("sidebar"), mobile=document.getElementById("mobileMenu");
        sidebar?.classList.remove("open"); mobile?.setAttribute("aria-expanded","false");
      });
      navContainer.appendChild(b);
    });
    if(typeof filterSessions==="function") filterSessions();
  }
  rebuild();
  window.addEventListener("storage",e=>{if(e.key===KEY) rebuild();});
})();